    # ---- 1. Single-sequence (backward-compat path) ----
    query = "ACDEFGHIKLMNPQRSTVWY"
    feat_single = encode_single_sequence(query)
    assert feat_single.features.shape == (1, len(query), FEATURE_DIM), \
        f"Expected (1, {len(query)}, {FEATURE_DIM}), got {feat_single.features.shape}"
    assert feat_single.deletion.sum() == 0, "No gaps expected for ungapped query"
    print(f"[1] Single-sequence: features {feat_single.features.shape}  (PASS)")

    # ---- 2. Pseudo-MSA generation ----
    msa_seqs = generate_pseudo_msa(query, n_sequences=7, mutation_rate=0.2, seed=42)
    assert len(msa_seqs) == 8, f"Expected 8 seqs, got {len(msa_seqs)}"
    assert msa_seqs[0] == query, "First sequence must be the unchanged query"
    assert all(len(s) == len(query) for s in msa_seqs), "All seqs must share length"
    print(f"[2] Pseudo-MSA:  {len(msa_seqs)} seqs x L={len(query)}  (PASS)")

    # ---- 3. Full MSA encoding ----
    enc = MSAEncoder()
    feat = enc.encode(msa_seqs)
    assert feat.features.shape == (8, len(query), FEATURE_DIM)
    assert feat.n_seq == 8
    assert feat.seq_len == len(query)
    assert not feat.is_pseudo
    print(f"[3] Encoded MSA:  {feat.features.shape}  (PASS)")

    # ---- 4. One-hot sanity: argmax should recover query tokens ----
    from src.data.protein_dataset import AA_TO_IDX as A2I
    expected_tokens = [A2I.get(aa, UNK_IDX) for aa in query]
    query_oh = feat.one_hot[0]                   # (L, 22)
    recovered = query_oh.argmax(dim=-1).tolist()
    assert recovered == expected_tokens, f"Token mismatch: {recovered} vs {expected_tokens}"
    print(f"[4] One-hot argmax recovers query tokens  (PASS)")

    # ---- 5. Profile sums to 1 at each position ----
    profile_sum = feat.profile[0].sum(dim=-1)    # (L,)
    assert torch.allclose(profile_sum, torch.ones(len(query)), atol=1e-5), \
        "Profile rows should sum to 1"
    print(f"[5] Profile sums to 1 at each position  (PASS)")

    # ---- 6. Gap / deletion handling ----
    gapped_seqs = ["ACDEF", "A-DEF", "ACD-F"]   # two gap positions
    feat_gap = enc.encode(gapped_seqs)
