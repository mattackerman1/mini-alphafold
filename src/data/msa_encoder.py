    # ---- 7. Feature slice properties ----
    assert feat.one_hot.shape  == (8, len(query), ONE_HOT_DIM)
    assert feat.deletion.shape == (8, len(query), DELETION_DIM)
    assert feat.profile.shape  == (8, len(query), ONE_HOT_DIM)
    assert feat.query_features().shape == (len(query), FEATURE_DIM)
    print(f"[7] Slice properties  (PASS)")

